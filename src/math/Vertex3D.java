package math;

public class Vertex3D {
	
	public double x;
	public double y;
	public double z;
	
	
	public Vertex3D(double x, double y, double z) {
		
		this.x = x;
		this.y = y;
		this.z = z;
	}


	public double getX() {
		return x;
	}


	public double getY() {
		return y;
	}


	public double getZ() {
		return z;
	}
	

}
